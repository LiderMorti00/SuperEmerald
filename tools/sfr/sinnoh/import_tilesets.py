#!/usr/bin/env python3
"""Super Emerald: import the tilesets used by the Sinnoh maps (LiderMorti00's own FireRed-style
tilesets). They keep the Emerald format, so they are copied as they are, renamed with a _Sinnoh
suffix (the Sinnoh repo repainted Emerald tilesets that keep their Emerald names).
Writes src/data/tilesets/sinnoh/{graphics,metatiles,headers,tileset_anims}.h."""
import json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import sin, ours, read, write, sinnoh_maps

# Animation callbacks: secondaries reuse ours (same animation frames as the Sinnoh repo);
# the general tileset has its own flowers, so it gets a Sinnoh copy of the General animations.
OUR_ANIMS = set(re.findall(r'^void (InitTilesetAnim_\w+)\(void\)', read(ours('src/tileset_anims.c')), re.M))

L = {l['id']: l for l in json.load(open(sin('data/layouts/layouts.json')))['layouts'] if 'primary_tileset' in l}
needed = set()
for grp, m in sinnoh_maps():
    l = L[json.load(open(sin('data/maps', m, 'map.json')))['layout']]
    needed |= {l['primary_tileset'], l['secondary_tileset']}

H_GFX = read(sin('src/data/tilesets/graphics.h')) + read(sin('src/graphics.c'))
H_MET = read(sin('src/data/tilesets/metatiles.h'))
H_HDR = read(sin('src/data/tilesets/headers.h'))

g_out, m_out, h_out = [], [], []
for t in sorted(needed):
    n = t[len('gTileset_'):]
    hb = re.search(r'const struct Tileset %s =\s*\{(.*?)\};' % t, H_HDR, re.S).group(1)
    tiles = re.search(r'\.tiles = (\w+)', hb).group(1)
    pals = re.search(r'\.palettes = (\w+)', hb).group(1)
    mets = re.search(r'\.metatiles = (\w+)', hb).group(1)
    path = re.search(r'%s\[\] = \w+\("([^"]+)/tiles' % tiles, H_GFX).group(1)
    sec = re.search(r'\.isSecondary = (\w+)', hb).group(1)
    newpath = path + '_sinnoh'
    shutil.rmtree(ours(newpath), ignore_errors=True)
    shutil.copytree(sin(path), ours(newpath), ignore=shutil.ignore_patterns('*.4bpp', '*.lz', '*.smol', '*.fastSmol', '*.gbapal'))
    palfiles = sorted(f for f in os.listdir(ours(newpath, 'palettes')) if re.fullmatch(r'\d\d\.pal', f))
    nn = n + '_Sinnoh'
    g_out.append('const u32 gTilesetTiles_%s[] = INCGFX_U32("%s/tiles.png", ".4bpp.smol");\n\n'
                 'const u16 gTilesetPalettes_%s[][16] =\n{\n%s};\n'
                 % (nn, newpath, nn, ''.join('    INCGFX_U16("%s/palettes/%s", ".gbapal"),\n' % (newpath, p) for p in palfiles)))
    m_out.append('const u16 gMetatiles_%s[] = INCBIN_U16("%s/metatiles.bin");\n'
                 'const u16 gMetatileAttributes_%s[] = INCBIN_U16("%s/metatile_attributes.bin");\n' % (nn, newpath, nn, newpath))
    cb = re.search(r'\.callback = (\w+)', hb)
    cb = cb.group(1) if cb else 'NULL'
    if cb == 'InitTilesetAnim_General':
        cb = 'InitTilesetAnim_General_Sinnoh'
    elif cb not in OUR_ANIMS:
        cb = 'NULL'
    h_out.append('const struct Tileset gTileset_%s =\n{\n    .isCompressed = TRUE,\n    .isSecondary = %s,\n'
                 '    .tiles = gTilesetTiles_%s,\n    .palettes = gTilesetPalettes_%s,\n'
                 '    .metatiles = gMetatiles_%s,\n    .metatileAttributes = gMetatileAttributes_%s,\n'
                 '    .callback = %s,\n};\n' % (nn, sec, nn, nn, nn, nn, cb))

hdr = '// Super Emerald: generated by tools/sfr/sinnoh/import_tilesets.py from LiderMorti00\'s Sinnoh repo.\n\n'
write(ours('src/data/tilesets/sinnoh/graphics.h'), hdr + '\n'.join(g_out))
write(ours('src/data/tilesets/sinnoh/metatiles.h'), hdr + '\n'.join(m_out))
write(ours('src/data/tilesets/sinnoh/headers.h'), hdr + '\n'.join(h_out))

# General animations with the Sinnoh flowers (the rest of the frames are the same as ours)
anim = hdr + '''static const u16 sTilesetAnims_GeneralSinnoh_Flower_Frame0[] = INCGFX_U16("data/tilesets/primary/general_sinnoh/anim/flower/0.png", ".4bpp");
static const u16 sTilesetAnims_GeneralSinnoh_Flower_Frame1[] = INCGFX_U16("data/tilesets/primary/general_sinnoh/anim/flower/1.png", ".4bpp");
static const u16 sTilesetAnims_GeneralSinnoh_Flower_Frame2[] = INCGFX_U16("data/tilesets/primary/general_sinnoh/anim/flower/2.png", ".4bpp");
static const u16 *const sTilesetAnims_GeneralSinnoh_Flower[] = {
    sTilesetAnims_GeneralSinnoh_Flower_Frame0,
    sTilesetAnims_GeneralSinnoh_Flower_Frame1,
    sTilesetAnims_GeneralSinnoh_Flower_Frame0,
    sTilesetAnims_GeneralSinnoh_Flower_Frame2
};

static void TilesetAnim_GeneralSinnoh(u16 timer)
{
    if (timer % 16 == 0)
        AppendTilesetAnimToBuffer(sTilesetAnims_GeneralSinnoh_Flower[(timer / 16) % ARRAY_COUNT(sTilesetAnims_GeneralSinnoh_Flower)], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(508)), 4 * TILE_SIZE_4BPP);
    if (timer % 16 == 1)
        QueueAnimTiles_General_Water(timer / 16);
    if (timer % 16 == 2)
        QueueAnimTiles_General_SandWaterEdge(timer / 16);
    if (timer % 16 == 3)
        QueueAnimTiles_General_Waterfall(timer / 16);
    if (timer % 16 == 4)
        QueueAnimTiles_General_LandWaterEdge(timer / 16);
}

void InitTilesetAnim_General_Sinnoh(void)
{
    sPrimaryTilesetAnimCounter = 0;
    sPrimaryTilesetAnimCounterMax = 256;
    sPrimaryTilesetAnimCallback = TilesetAnim_GeneralSinnoh;
}
'''
write(ours('src/data/tilesets/sinnoh/tileset_anims.h'), anim)
print('tilesets', len(needed))
