#!/usr/bin/env python3
"""Super Emerald: write data/scripts/se_sinnoh_state.inc, the post-story state of Sinnoh.

Every story object (Team Galactic, Barry, Rowan's and Dawn's story scenes, Looker...) is hidden,
legendaries stay hidden until their map shows them (se_sinnoh.inc), and the few post-game NPCs
are shown. Run again (and bump SE_SINNOH_STATE_VERSION in vars.h) when the rules change."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ours, read, write

flags = re.findall(r'#define (FLAG_\w+)\s+0x[0-9a-f]+', read(ours('include/constants/flags_sinnoh.h')))
# shown in the post-story world
KEEP = r'CYCLE_SHOP_OWNER|_BG_|MYSTERY_GIFT_MAN|VILLA_PTNPC|VILLA_OWNER|HALL_SPEECH'
sets, clears = [], []
for f in flags:
    if f.startswith('FLAG_SINNOH_BADGE') or f == 'FLAG_SE_SINNOH_INITIALIZED' or 'ITEM' in f or 'DAILY' in f:
        continue
    if 'HIDE' in f:
        (clears if re.search(KEEP, f) else sets).append(f)

out = ['@ Super Emerald: generated by tools/sfr/sinnoh/gen_sinnoh_state.py - do not edit by hand.',
       '@ Post-story state of Sinnoh (LiderMorti00\'s Sinnoh repo maps).', '',
       'SE_EventScript_InitSinnoh::',
       '\tsetflag FLAG_SE_SINNOH_INITIALIZED',
       '\tcall SE_EventScript_SinnohWorldState',
       '\treturn', '',
       'SE_EventScript_SinnohWorldState::']
out += ['\tsetflag %s' % f for f in sets]
out += ['\tclearflag %s' % f for f in clears]
out += ['\tsetvar VAR_SN_SINNOH_STORY, SN_SINNOH_STORY_DONE', '\tsetvar VAR_SE_SINNOH_STATE_VERSION, SE_SINNOH_STATE_VERSION', '\treturn', '']
write(ours('data/scripts/se_sinnoh_state.inc'), '\n'.join(out))
print('hidden', len(sets), 'shown', len(clears))
