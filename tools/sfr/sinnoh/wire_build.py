#!/usr/bin/env python3
"""Super Emerald: hook the imported Sinnoh data into the build (script includes, trainer
tables, flags). Safe to run again."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ours, read, write

B, E = '@ Super Emerald: Sinnoh begin (generated by tools/sfr/sinnoh/wire_build.py)', '@ Super Emerald: Sinnoh end'
g = json.load(open(ours('data/maps/map_groups.json')))
maps = [m for grp in g['group_order'] if grp.endswith('_Sinnoh') for m in g[grp]]
p = ours('data/event_scripts.s'); s = read(p)
s = re.sub(re.escape(B) + r'.*?' + re.escape(E) + r'\n', '', s, flags=re.S)
inc = ''.join('\t.include "data/maps/%s/scripts.inc"\n' % m for m in maps)
inc += '\t.include "data/scripts/se_sinnoh_import.inc"\n'
for extra in ('data/scripts/se_sinnoh_state.inc', 'data/scripts/se_sinnoh.inc', 'data/scripts/se_sinnoh_legendaries.inc'):
    if os.path.exists(ours(extra)):
        inc += '\t.include "%s"\n' % extra
anchor = '@ Super Emerald: HnS end\n'
s = s.replace(anchor, anchor + B + '\n' + inc + E + '\n', 1)
write(p, s)
print('map scripts', len(maps))
