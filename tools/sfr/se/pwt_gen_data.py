#!/usr/bin/env python3
# Super Emerald: generates src/data/battle_frontier/se_pwt.h (PWT roster, teams and roles)
# from pwt_roster.py (base teams), pwt_variants.py and pwt_b2w2_regional.txt (cup variants).
# Run from the repo root: python3 tools/sfr/se/pwt_gen_data.py
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
from pwt_roster import R, EV
from pwt_variants import REGIONAL, WORLD, CHAMPIONS_CUP, EXTRA_LEADERS

def consts(path, prefix):
    return set(re.findall(r'\b(%s[A-Z0-9_]+)\b' % prefix, open(os.path.join(ROOT, path)).read()))
SPECIES = consts('include/constants/species.h', 'SPECIES_')
ITEMS = consts('include/constants/items.h', 'ITEM_')
MOVES = consts('include/constants/moves.h', 'MOVE_')

# move categories, for the natures and EVs of the B2W2 teams
CAT = {}
cur = None
for line in open(os.path.join(ROOT, 'src/data/moves_info.h')):
    m = re.match(r'\s*\[(MOVE_\w+)\]\s*=', line)
    if m:
        cur = m.group(1)
    m = re.search(r'\.category = DAMAGE_CATEGORY_(\w+)', line)
    if m and cur and cur not in CAT:
        CAT[cur] = m.group(1)

def norm(s):
    return re.sub(r'[^A-Z0-9]+', '_', s.upper().replace('.', '').replace("'", '')).strip('_')

def b2w2_mon(name, item, moves):
    moves = [norm(m) for m in moves.split(',')]
    phys = sum(CAT.get('MOVE_' + m) == 'PHYSICAL' for m in moves)
    spec = sum(CAT.get('MOVE_' + m) == 'SPECIAL' for m in moves)
    if phys == 0 and spec == 0:
        nat, ev = 'BOLD', 'B'
    elif phys > spec or (phys == spec and CAT.get('MOVE_' + moves[0]) == 'PHYSICAL'):
        nat, ev = 'ADAMANT', 'P'
    else:
        nat, ev = 'MODEST', 'S'
    return '%s|%s|%s|%s|%s' % (norm(name), norm(item), nat, ev, ','.join(moves))

B2W2 = {}
for line in open(os.path.join(HERE, 'pwt_b2w2_regional.txt')):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    key, name, item, moves = line.split('|')
    B2W2.setdefault(key, []).append(b2w2_mon(name, item, moves))
for k in B2W2:
    assert k not in REGIONAL, k
REGIONAL = dict(REGIONAL, **B2W2)

KEYS = [r[0] for r in R]
for k in list(REGIONAL) + list(WORLD) + CHAMPIONS_CUP:
    assert k in KEYS, k

errors = []
mons = []
def add_team(owner, team):
    assert len(team) == 6, (owner, len(team))
    ids, seen_items, seen_species = [], set(), set()
    for m in team:
        sp, it, na, e, ms = m.split('|')
        for c in ['SPECIES_' + sp] + ['MOVE_' + x for x in ms.split(',')]:
            if c not in SPECIES and c not in MOVES:
                errors.append('%s: unknown %s' % (owner, c))
        if 'ITEM_' + it not in ITEMS:
            errors.append('%s: unknown ITEM_%s' % (owner, it))
        if it in seen_items or sp in seen_species:
            errors.append('%s: duplicate %s/%s' % (owner, sp, it))
        seen_items.add(it); seen_species.add(sp)
        assert e in EV, (owner, e)
        ids.append(len(mons))
        mons.append((sp, it, na, e, ms))
    return ids

base = {r[0]: add_team(r[0], r[7]) for r in R}            # keeps the old indices: 0..N-1 in roster order
regional = {k: add_team(k + '/regional', REGIONAL[k]) for k in KEYS if k in REGIONAL}
world = {k: add_team(k + '/world', WORLD[k]) for k in KEYS if k in WORLD}
if errors:
    sys.exit('\n'.join(errors))

REG = {'K': 'SE_PWT_KANTO', 'J': 'SE_PWT_JOHTO', 'H': 'SE_PWT_HOENN', 'S': 'SE_PWT_SINNOH', 'X': 'SE_PWT_KALOS', 'U': 'SE_PWT_UNOVA'}
RANK = {'L': 'SE_PWT_RANK_LEADER', 'E': 'SE_PWT_RANK_ELITE', 'C': 'SE_PWT_RANK_CHAMPION', 'B': 'SE_PWT_RANK_BRAIN', 'T': 'SE_PWT_RANK_TRAINER'}
leader_regions = {}
for r in R:
    regs = r[5] if r[6] == 'L' else ''
    regs += EXTRA_LEADERS.get(r[0], '')
    leader_regions[r[0]] = regs
    if regs:
        assert r[0] in REGIONAL, 'leader without a regional team: ' + r[0]
for k in REGIONAL:
    assert leader_regions[k], 'regional team for a non-leader: ' + k

SPEECH = ('EC_WORD_I_AM, EC_WORD_NEVER, EC_WORD_GOING, EC_WORD_TO, EC_WORD_LOSE, EC_WORD_EXCL',
          'EC_WORD_A, EC_WORD_WIN, EC_WORD_IS, EC_WORD_JUST, EC_WORD_AWESOME, EC_EMPTY_WORD',
          'EC_WORD_YOU, EC_WORD_WON, EC_WORD_EXCL, EC_WORD_MOVE, EC_WORD_ON, EC_WORD_EXCL')

o = '// Super Emerald: Pokemon World Tournament (Johto) roster. Generated by tools/sfr/se/pwt_gen_data.py\n'
o += '// from pwt_roster.py, pwt_variants.py and pwt_b2w2_regional.txt. Do not edit by hand.\n\n'
o += 'const struct TrainerMon gSEPwtMons[] =\n{\n'
for i, (sp, it, na, e, ms) in enumerate(mons):
    mv = ', '.join('MOVE_' + x for x in ms.split(','))
    o += ('    [%d] = {\n        .species = SPECIES_%s,\n        .moves = {%s},\n        .heldItem = ITEM_%s,\n'
          '        .ev = TRAINER_PARTY_EVS(%s),\n        .nature = NATURE_%s,\n        .ball = BALL_POKE\n    },\n') % (i, sp, mv, it, EV[e], na)
o += '};\n\n'

def trainers(name, comment, sets):
    s = '// %s\nconst struct BattleFrontierTrainer %s[] =\n{\n' % (comment, name)
    for r in R:
        s += ('    [SE_PWT_TRAINER_%s] = {\n        .facilityClass = FACILITY_CLASS_SE_%s,\n        .trainerName = _("%s"),\n'
              '        .speechBefore = {%s},\n        .speechWin = {%s},\n        .speechLose = {%s},\n'
              '        .monSet = (const u16[]){%s, 0xFFFF}\n    },\n') % (
            r[0], r[0], r[1][:7], SPEECH[0], SPEECH[1], SPEECH[2], ', '.join(map(str, sets.get(r[0], base[r[0]]))))
    return s + '};\n\n'

o += trainers('gSEPwtTrainers', 'CHAMPIONS CUP and default teams (leaders: World Leaders teams; champions: Champions teams)', {})
o += trainers('gSEPwtTrainersRegional', 'Regional LEADERS cups: the leaders bring their regional team', regional)
o += trainers('gSEPwtTrainersWorld', 'WORLD CUP: the champions bring their World team', world)
o += 'const u8 *const gSEPwtNames[] =\n{\n' + ''.join('    [SE_PWT_TRAINER_%s] = COMPOUND_STRING("%s"),\n' % (r[0], r[1]) for r in R) + '};\n\n'
o += 'const u16 gSEPwtGfx[] =\n{\n' + ''.join('    [SE_PWT_TRAINER_%s] = OBJ_EVENT_GFX_%s,\n' % (r[0], r[3]) for r in R) + '};\n\n'
o += 'const u8 gSEPwtRegions[] =\n{\n' + ''.join('    [SE_PWT_TRAINER_%s] = %s,\n' % (r[0], ' | '.join('(1 << %s)' % REG[c] for c in r[5])) for r in R) + '};\n\n'
o += 'const u8 gSEPwtRanks[] =\n{\n' + ''.join('    [SE_PWT_TRAINER_%s] = %s,\n' % (r[0], RANK[r[6]]) for r in R) + '};\n\n'
o += '// Regions where the trainer is a gym leader (regional LEADERS cups)\nconst u8 gSEPwtLeaderRegions[SE_PWT_TRAINERS_COUNT] =\n{\n'
o += ''.join('    [SE_PWT_TRAINER_%s] = %s,\n' % (k, ' | '.join('(1 << %s)' % REG[c] for c in leader_regions[k])) for k in KEYS if leader_regions[k]) + '};\n\n'
o += '// The champions of the CHAMPIONS CUP\nconst bool8 gSEPwtInChampionsCup[SE_PWT_TRAINERS_COUNT] =\n{\n'
o += ''.join('    [SE_PWT_TRAINER_%s] = TRUE,\n' % k for k in CHAMPIONS_CUP) + '};\n'
o = o.replace('\n};\n\nconst u8 gSEPwtLeaderRegions', '\n};\n\nconst u8 gSEPwtLeaderRegions')
out = os.path.join(ROOT, 'src/data/battle_frontier/se_pwt.h')
if not os.path.exists(out) or open(out).read() != o:
    open(out, 'w').write(o)
print('%d mons, %d regional teams, %d world teams' % (len(mons), len(regional), len(world)))
