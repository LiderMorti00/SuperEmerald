#!/usr/bin/env python3
"""Super Emerald: Sinnoh music from pret/pokeplatinum.
The Platinum sequences (res/sound/SEQ) are expanded to plain MIDIs by sseqmid2agbmid.py.
Platinum's banks follow General MIDI program numbers (drum kits at 1, 6 and 16), so the
voicegroup sinnoh_pt is indexed by those numbers and uses the Gen 4 instrument samples
already in the ROM (HGSS voicegroup 229) where there is one, else the GM voicegroup sinnoh_gm.
usage: gen_sinnoh_music.py /path/to/pokeplatinum"""
import sys,os,re
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.join(HERE,'../../..'); os.chdir(ROOT)
sys.path.insert(0,HERE)
import sseqmid2agbmid as conv
exec(open(os.path.join(HERE,'dpp_song_map.py')).read())
PLAT=sys.argv[1]
def vlines(p):
    return [l.strip() for l in open(p).read().split('\n') if l.strip().startswith('voice_') and not l.strip().startswith('voice_group')]
gm=vlines('sound/voicegroups/sinnoh_gm.inc')
hg=vlines('sound/voicegroups/voicegroup229.inc')
hgx=[l.lstrip('@').strip() for l in open('sound/voicegroups/voicegroup229.inc').read().split('\n') if l.strip().startswith('@\tvoice_') or l.strip().startswith('@ voice_') or l.strip().startswith('@voice_')]
# Platinum program -> HGSS voicegroup 229 entry
