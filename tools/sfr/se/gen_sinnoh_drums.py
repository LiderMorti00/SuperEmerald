#!/usr/bin/env python3
"""Super Emerald: drum kit for the Platinum sequences (voicegroup sinnoh_pt_drums).
Notes 28-69 reuse the Gen 4 kit already in the ROM (voicegroup230); the notes Platinum adds on
top (70-88) use Platinum's own samples, converted from pokeplatinum's WAVE_ARC_BASIC.
usage: gen_sinnoh_drums.py /path/to/pokeplatinum"""
import sys,os,struct,subprocess
HERE=os.path.dirname(os.path.abspath(__file__)); os.chdir(os.path.join(HERE,'../../..'))
PLAT=sys.argv[1]
def parse(name):
    L=open(os.path.join(PLAT,'res/sound/BANK/%s.txt'%name)).read().split('\n'); P={};cur=None
    for l in L:
        if not l.strip(): continue
        if l.startswith('\t'): P[cur]['regions'].append([x.strip() for x in l.strip().split(',')])
        else:
            f=[x.strip() for x in l.split(',')]; cur=int(f[0]); P[cur]={'type':f[1],'raw':f[2:],'regions':[]}
    return P
regs=parse('BANK_BGM_FIELD')[1]['regions']
v=[l.strip().split('@')[0].strip() for l in open('sound/voicegroups/voicegroup230.inc') if l.strip().startswith('voice_')]
def mkwav(idx):
    name='pt_drum_%03d'%idx
    path='sound/direct_sound_samples/%s.wav'%name
    src=os.path.join(PLAT,'res/sound/WAVARC/WAVE_ARC_BASIC/%03d.wav'%idx)
    rate=int(float(subprocess.check_output(['ffprobe','-v','error','-show_entries','stream=sample_rate','-of','csv=p=0',src]).decode()))
    orig=rate; rate=min(rate,11025)  # halve the size of 16 kHz samples, still clear on the GBA mixer
    pcm=subprocess.check_output(['ffmpeg','-v','error','-i',src,'-ar',str(rate),'-f','u8','-ac','1','-'])
    smpl=struct.pack('<9I',0,0,int(1e9/rate),60,0,0,0,0,0)
    fmt=struct.pack('<HHIIHH',1,1,rate,rate,1,8)
    body=b'fmt '+struct.pack('<I',16)+fmt+b'smpl'+struct.pack('<I',len(smpl))+smpl+b'data'+struct.pack('<I',len(pcm))+pcm+(b'\0' if len(pcm)&1 else b'')
    open(path,'wb').write(b'RIFF'+struct.pack('<I',4+len(body))+b'WAVE'+body)
    return name
used=set()
out=['voice_group sinnoh_pt_drums @ Generated by tools/sfr/se/gen_sinnoh_drums.py']
for n in range(128):
    if n<70 and n<len(v) and n>=28 or (n<28 and n<len(v)):
        out.append('\t'+v[n]); continue
    if 70<=n<=88:
        r=regs[n-28]; s=int(r[1]); base=int(r[3]); att,dec,sus,rel,pan=map(int,r[4:9])
        name=mkwav(s); used.add(name)
        key=60+(n-base)
        # DS ADSR (0-127) -> m4a (attack 255 = instant)
        a=255 if att>=127 else max(1,att*2); d=dec*2 if dec<127 else 0; su=sus*2 if sus<127 else 255; re_=171
        out.append('\tvoice_directsound %d, %d, DirectSoundWaveData_%s, %d, %d, %d, %d'%(key,pan,name,a,d,su,re_)); continue
    out.append('\tvoice_directsound 60, 0, DirectSoundWaveData_dp_bassdr1, 255, 0, 0, 0')  # silent filler
open('sound/voicegroups/sinnoh_pt_drums.inc','w').write('\n'.join(out)+'\n')
vg=open('sound/voice_groups.inc').read()
if 'sinnoh_pt_drums.inc' not in vg:
    vg=vg.replace('.include "sound/voicegroups/sinnoh_pt.inc"\n','.include "sound/voicegroups/sinnoh_pt.inc"\n.include "sound/voicegroups/sinnoh_pt_drums.inc"\n'); open('sound/voice_groups.inc','w').write(vg)
ds=open('sound/direct_sound_data.inc').read()
for n in sorted(used):
    if 'DirectSoundWaveData_%s::'%n not in ds:
        ds+='\n\t.align 2\nDirectSoundWaveData_%s::\n\t.incbin "sound/direct_sound_samples/%s.bin"\n'%(n,n)
open('sound/direct_sound_data.inc','w').write(ds)
print(sorted(used))
