def fix_value(kind, v):
    if kind == 'Class':
        if v in CLASS_FIX: return CLASS_FIX[v]
        b = v[:-4] if v.endswith(' Hns') else v
        for c in (b + ' Frlg', b):
            if has(tconst('TRAINER_CLASS_', c)): return c
        return 'Pkmn Trainer 1'
    if kind == 'Pic':
        if v in PIC_FIX: return PIC_FIX[v]
        b = v[:-4] if v.endswith(' Hns') else v
        for c in (v, b + ' Frlg', b):
            if has(tconst('TRAINER_PIC_', c)): return c
        return 'Youngster Frlg'
    if kind == 'Music':
        if v in MUSIC_FIX: return MUSIC_FIX[v]
        return v if has(tconst('TRAINER_ENCOUNTER_MUSIC_', v)) else 'Male'
    return v

def fix_block(b):
    out, mons = [], b.split('\n\n')
    head = mons[0].split('\n')
    for line in head:
        k, sep, v = line.partition(': ')
        if k == 'Mugshot':
            continue
        out.append(k + sep + fix_value(k, v) if sep and k in ('Class', 'Pic', 'Music') else line)
    res = ['\n'.join(out)]
    for mon in mons[1:]:
        lines = mon.split('\n')
        if not lines or not lines[0].strip():
            res.append(mon); continue
        lv = re.search(r'^Level: (\d+)', mon, re.M)
        L = scale(int(lv.group(1))) if lv else 50
        m = re.match(r'^(?:(.*?) \()?([^()@]+?)\)?(\s*\([MF]\))?(\s*@.*)?$', lines[0])
        first = lines[0]
        if m:
            sp = species_const(m.group(2))
            if sp in SPECIES:
                sp2 = evolve(sp, L)
                nick = m.group(1)
                first = ('%s (%s)' % (nick, sp2) if nick else sp2) + (m.group(3) or '') + (m.group(4) or '')
        lines[0] = first
        lines = [('Level: %d' % L) if l.startswith('Level: ') else l for l in lines if not l.startswith('IVs: 0 HP / 0 Atk')]
        res.append('\n'.join(lines))
    return '\n\n'.join(res)

