#!/usr/bin/env python3
"""Super Emerald: import the Johto maps from Pokemon Heart & Soul as a post-story free world.

For every HnS map whose map section is in Johto (see common.johto_maps):
  * layout (map.bin/border.bin) copied, registered as an FRLG-style layout;
  * map.json converted (object events typed, music mapped, coord events dropped,
    connections/warps to maps we don't import remapped or dropped);
  * map groups: the HnS group names, Johto maps only.
Scripts: each object/sign script is copied from HnS only if every command and constant it
uses exists here (HnS flags become Johto extended flags, HnS trainers Johto trainers).
Scripts that depend on the HnS story (story vars, specials we don't have, ...) are replaced:
trainers get a plain trainerbattle with their HnS texts, NPCs and signs say their first
HnS line. Labels defined in a Johto map go to that map's scripts.inc; labels from HnS
shared files go to data/scripts/se_johto_hns.inc.
Also writes include/constants/flags_johto.h, opponents_johto_list.h,
src/data/trainers_johto.party and the list of story objects hidden in the free world.

Usage (repo root): python3 -I tools/sfr/hns/import_maps.py [--hns /path]
"""
