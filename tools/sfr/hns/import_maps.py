def map_music(m, mus):
    if mus == 'MUS_HG_POKE_MART' or (mus not in OUR_SONGS and mus not in MUSIC_MAP):
        t = town_music.get(m.split('_')[0])
        return MUSIC_MAP.get(t, t) if t in OUR_SONGS or t in MUSIC_MAP else 'MUS_HG_ROUTE30'
    return MUSIC_MAP.get(mus, mus)

