# Johto is a post-story region at the same level as Kanto: HnS levels (2-50 in the
# story) are spread over 47-62 like the Kanto HGSS trainers, and the Pokemon evolve.
LOW, HIGH = 47, 62
SPECIES = set(re.findall(r'\b(SPECIES_\w+)\b', read(ours('include/constants/species.h'))))
EVOS = {}
for f in glob.glob(ours('src/data/pokemon/species_info/*.h')):
    for m in re.finditer(r'\[(SPECIES_\w+)\]\s*=\s*\{(.*?)\n    \},', read(f), re.S):
        e = re.search(r'\.evolutions = EVOLUTION\((.*?)\),(?:\n|$)', m.group(2), re.S)
        if e:
            EVOS.setdefault(m.group(1), re.findall(r'\{(EVO_\w+),\s*([^,]+),\s*(SPECIES_\w+)', e.group(1)))

def species_const(name):
    n = name.strip().replace('♂', '_M').replace('♀', '_F').replace('é', 'E').replace('’', '').replace("'", '')
    n = re.sub(r'[^A-Za-z0-9]+', '_', n).strip('_').upper()
    return 'SPECIES_' + n

def evolve(sp, lvl):
    for _ in range(3):
        nxt = None
        for meth, param, tgt in EVOS.get(sp, []):
            if tgt not in SPECIES:
                continue
            if meth == 'EVO_LEVEL' and param.strip().isdigit() and int(param) <= lvl:
                nxt = tgt; break
            if meth in ('EVO_ITEM', 'EVO_TRADE') and lvl >= 45:
                nxt = tgt; break
            if meth == 'EVO_LEVEL' and not param.strip().isdigit() and lvl >= 45:
                nxt = tgt; break
        if not nxt:
            return sp
        sp = nxt
    return sp

def scale(L):
    if L <= 50:
        return round(LOW + (L - 2) * (HIGH - LOW) / 48.0)
    return min(70, round(HIGH + (L - 50) * 0.2))

