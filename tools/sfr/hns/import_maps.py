johto_trainers = collections.OrderedDict()
BERRY_IDS = collections.OrderedDict()

def flag_name(f):
    if f in BADGES:
        return BADGES[f]
    if f in SAFE_OUR_FLAGS:
        return f
    if f in OUR_CONST:          # same name means something else here: rename
        n = 'FLAG_J' + f[len('FLAG'):]
    else:
        n = f
    johto_flags.setdefault(f, n)
    return n

# ---------------------------------------------------------------- script analysis
TOKEN = re.compile(r'\b([A-Za-z_]\w*)\b')

def closure(entry):
    seen, stack = [], [entry]
    while stack:
        l = stack.pop()
        if l in seen or l not in LABELS or l in OUR_LABELS:
            continue
        seen.append(l)
        for line in LABELS[l][1]:
            if line.strip().startswith('.string'):
                continue
            for t in TOKEN.findall(line.split('@')[0]):
                if t in LABELS and t not in OUR_LABELS:
                    stack.append(t)
    return seen

def check_line(line, local_ids):
    """Return None if the line is fine, else a reason."""
    code = line.split('@')[0].strip()
    if not code or code.startswith('.string'):
        return None
    cmd = code.split()[0].rstrip(',')
    if cmd not in OUR_MACROS:
        return 'cmd ' + cmd
    args = code[len(cmd):]
    if cmd in ('special', 'specialvar'):
        sp = args.split(',')[-1].strip()
        if sp not in OUR_SPECIALS:
            return 'special ' + sp
    if cmd in ('callnative', 'gotonative'):
        return 'native'
    for t in TOKEN.findall(args):
        if t in LABELS or t in OUR_LABELS or t in local_ids:
            continue
        if t.startswith('VAR_'):
            if t not in ALLOWED_VARS:
                return 'var ' + t
            continue
        if t.startswith('FLAG_'):
            if t.startswith('FLAG_SYS_') and t not in SAFE_OUR_FLAGS:
                return 'flag ' + t
            if t in H_FLAGS or t in OUR_CONST or t in BADGES:
                continue
            return 'flag ' + t
        if t.startswith('TRAINER_') and t.endswith('_HNS'):
            continue
        if t.startswith('MUS_'):
            if t in OUR_SONGS or t in MUSIC_MAP:
                continue
            return 'music ' + t
        if t.startswith('MAP_'):
            if t in IDS or t in OUR_CONST:
                continue
            return 'map ' + t
        if t in ('TRUE', 'FALSE', 'YES', 'NO', 'ON', 'OFF'):
            continue
        if re.fullmatch(r'[A-Z][A-Z0-9_]+', t) and t not in OUR_CONST:
            return 'const ' + t
        if re.fullmatch(r'[a-z]\w*', t) or t in ('TRUE', 'FALSE', 'YES', 'NO'):
            continue
    return None

def convert_line(line):
    def rep(m):
        t = m.group(1)
        if t.startswith('FLAG_') and (t in H_FLAGS or t in BADGES) and t not in SAFE_OUR_FLAGS:
            return flag_name(t)
        if t in MUSIC_MAP:
            return MUSIC_MAP[t]
        if t.startswith('TRAINER_') and t.endswith('_HNS'):
            johto_trainers.setdefault(t, None)
        return t
    if line.strip().startswith('.string'):
        return line
    code, sep, cmt = line.partition('@')
    return TOKEN.sub(rep, code) + sep + cmt

def first(lines_by_label, pattern):
    for l in lines_by_label:
        for line in LABELS[l][1]:
            m = re.search(pattern, line)
            if m:
                return m
    return None

# ---------------------------------------------------------------- per map
OUT = collections.defaultdict(list)    # file -> list of label blocks
EMITTED = set()
STATS = collections.Counter()
REJECTS = collections.Counter()
FALLBACKS = []
FB_DONE = set()

def emit_label(label):
    if label in EMITTED:
        return
    EMITTED.add(label)
    om = owner_map(label)
    dest = ours('data/maps', om, 'scripts.inc') if om else ours('data/scripts/se_johto_hns.inc')
    body = [convert_line(x) for x in LABELS[label][1]]
    while body and not body[-1].strip():
        body.pop()
    OUT[dest].append('%s::\n%s\n' % (label, '\n'.join(body)))

def emit_text(label):
    """Copy a text label (only .string lines)."""
    if label in OUR_LABELS:
        return label
    emit_label(label)
    return label

def resolve(entry, kind, obj, local_ids, mapname):
    """Return the script label to use for an event."""
    if entry in ('', '0x0', 'NULL', None):
        return entry or '0x0'
    if entry in OUR_LABELS:
        return entry
    if entry not in LABELS:
        STATS['missing'] += 1
        return '0x0'
    cl = closure(entry)
    reason = None
    for l in cl:
        for line in LABELS[l][1]:
            reason = check_line(line, local_ids)
            if reason:
                break
        if reason:
            break
    if not reason:
        for l in cl:
            emit_label(l)
        STATS['kept'] += 1
        return entry
    REJECTS[reason.split()[0] + ' ' + reason.split()[1] if ' ' in reason else reason] += 1
    # ---- fallback
    fb = 'SE_J_%s_%s' % (mapname, entry)
    if fb in FB_DONE:
        return fb
    FB_DONE.add(fb)
    lines = None
    if kind == 'trainer':
        m = first(cl, r'trainerbattle_(single|double|no_intro)\s+(TRAINER_\w+)\s*,\s*(\w+)(?:\s*,\s*(\w+))?(?:\s*,\s*(\w+))?')
        after = first(cl, r'msgbox\s+(\w+)\s*,\s*MSGBOX_AUTOCLOSE')
        if m:
            t = m.group(2); johto_trainers.setdefault(t, None)
            if m.group(1) == 'no_intro':
                lines = ['\ttrainerbattle_no_intro %s, %s' % (t, emit_text(m.group(3)))]
            elif m.group(1) == 'double':
                lines = ['\ttrainerbattle_double %s, %s, %s, %s' % (t, emit_text(m.group(3)), emit_text(m.group(4)), emit_text(m.group(5)))]
            else:
                lines = ['\ttrainerbattle_single %s, %s, %s' % (t, emit_text(m.group(3)), emit_text(m.group(4)))]
            if after:
                lines.append('\tmsgbox %s, MSGBOX_AUTOCLOSE' % emit_text(after.group(1)))
            lines.append('\tend')
    if lines is None:
        m = first(cl, r'(?:msgbox|message)\s+(\w+)')
        if m and m.group(1) in LABELS:
            txt = emit_text(m.group(1))
            if kind == 'sign':
                lines = ['\tmsgbox %s, MSGBOX_SIGN' % txt, '\tend']
            else:
                lines = ['\tmsgbox %s, MSGBOX_NPC' % txt, '\tend']
        else:
            m = first(cl, r'finditem\s+(ITEM_\w+)')
            if m and m.group(1) in OUR_CONST:
                lines = ['\tfinditem %s' % m.group(1), '\tend']
            else:
                lines = ['\tend']
    om = mapname
    OUT[ours('data/maps', om, 'scripts.inc')].append('%s::\n%s\n' % (fb, '\n'.join(lines)))
    FALLBACKS.append((mapname, entry, reason))
    STATS['fallback'] += 1
    return fb

