#!/usr/bin/env python3
"""Super Emerald: writes data/scripts/se_johto_state.inc, the post-story state of the
Johto (HnS) world: which story objects are hidden and which story flags count as done.
Run after import_maps.py (it reads include/constants/flags_johto.h).

The script runs the first time the player enters Johto, and again whenever
SE_JOHTO_STATE_VERSION (include/constants/vars.h) is bumped.

Usage (repo root): python3 tools/sfr/hns/gen_johto_state.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ours, read, write

flags = re.findall(r'#define (FLAG_\w+)\s+0x[0-9a-f]+', read(ours('include/constants/flags_johto.h')))

# Story characters and events that are over once Johto's story has happened.
HIDE = r'ROCKET|SILVER|ARIANA|PETREL|PROTON|GIOVANNI|ARCHER|MURKROW|ELECTRODE|GRUNT|SCOUT|LANCE|' \
       r'DEN_CLAIR|DRAGONS_DEN_CAVERN_CLAIR|DRAGONS_DEN_SHRINE_CLAIR|EUSINE|SUICUNE|BEASTS|HO_OH|LUGIA|' \
       r'CELEBI|MOLTRES|RAYQUAZA|SHADOW|BILL|LAB_POLICEMAN|MOMS_FRIEND|OAK|SABRINA|AZALEA_ARIADOS|' \
       r'FARFETCHD|TAILLESS|AZALEA_TOWN_KURT|SLOWPOKE_WELL_KURT|ILEX_FOREST_MASTER|ILEX_FOREST_APPRENTICE|' \
       r'GUIDE_GENT|SSAQUA_1F_GRANDPA|GRANDDAUGHTER|SSAQUA_SAILOR|DEPTSTORE_WHITNEY|BELLCHIME_MORTY|' \
       r'CAFE_JASMINE|LIGHTHOUSE_JASMINE|LAKE_PRYCE|DOJO_|MAHOGANY_COP|MAHOGANY_TOWN_FATMAN|' \
       r'MAHOGANY_TOWN_SHOP_NPCS|ECRUTEAK_CITY_SAGE|SUDOWOODO|WHIRL_ISLANDS_TENTACRUEL|DECORATION|' \
       r'RADIOTOWER_DIRECTOR_2|RADIOTOWER_GATE|ROCKETHIDEOUT3_GATE|MRPOKEMON|ROUTE28_SCIENTIST|' \
       r'MT_SILVER_1F_HIDE_SCIENTIST|ICEPATH_B2F_BOULDER|KIMONO|BURNED_TOWER_NPCS|HIDE_TRAINER_SCHOOL_EARL|' \
       r'VIOLET_CITY_AIDE|BUG_CONTEST_ATTENDANT_SIDE|ITEM_DOME_FOSSIL|ITEM_HELIX_FOSSIL|ITEM_OLD_AMBER|' \
       r'CHIKORITABALL|CYNDAQUILBALL|TOTODILEBALL'
# ... but these stay: the Kimono Girls dance in the theater, Kurt works at home.
KEEP = r'THEATER_KIMONOS|THEATER_ZUKI|THEATER_NPCS|HIDE_KURT_1|HIDE_KURT_2'
# Story progress flags that should read as "done" (scripts check them).
DONE = r'^FLAG_(?:J_)?(?:ADVENTURE_STARTED|MOM_VISITED|DELIVERED_EGG|AMPHAROS_HEALED|RELEASED_BEASTS|' \
       r'GOT_HEADBUTT|GET_HEADBUTT|UNLOCKED_GOLDENROD_UNDERGROUND_DOOR|COMPLETED_SWITCHES|ENABLE_RADIO|' \
       r'RETURNED_MACHINE_PART|VISITED_KANTO|J_RECEIVED_BIKE)$'

sets, clears = [], []
for f in flags:
    if f.startswith('FLAG_JOHTO_BADGE') or f == 'FLAG_SE_JOHTO_INITIALIZED' or '_ITEM_' in f and 'FOSSIL' not in f and 'AMBER' not in f:
        continue
    if f in ('FLAG_DAY_POKEMON', 'FLAG_NIGHT_POKEMON'):
        continue
    if re.search(DONE, f):
        sets.append(f)
    elif re.search(r'HIDE|ITEM_', f):
        (clears if re.search(KEEP, f) or not re.search(HIDE, f) else sets).append(f)

out = ['@ Super Emerald: generated by tools/sfr/hns/gen_johto_state.py - do not edit by hand.',
       '@ Post-story state of Johto (Pokemon Heart & Soul maps).', '',
       'SE_EventScript_InitJohto::',
       '\tsetflag FLAG_SE_JOHTO_INITIALIZED',
       '\tcall SE_EventScript_JohtoWorldState',
       '\treturn', '',
       'SE_EventScript_JohtoWorldState::']
out += ['\tsetflag %s' % f for f in sets]
out += ['\tclearflag %s' % f for f in clears]
out += ['\tsetvar VAR_SE_JOHTO_STATE_VERSION, SE_JOHTO_STATE_VERSION', '\treturn', '']
write(ours('data/scripts/se_johto_state.inc'), '\n'.join(out))
print('hidden/done', len(sets), 'shown', len(clears))
