#!/usr/bin/env python3
"""Super Emerald: import the HnS tilesets used by the Johto maps.

HnS tilesets are 640/640/7 like FRLG but keep Emerald-style data, so each one is
converted to the format our FRLG layouts use:
  * metatile_attributes.bin: 2-byte (behavior 0x00FF, layer 0xF000) -> 4-byte FRLG
    (behavior 0x1FF, layer << 29). Behavior numbers are the same in both projects.
  * metatiles.bin: dual-layer (16 bytes) -> triple-layer (24 bytes), like
    tools/sfr/convert_triple_layer.py.
Writes src/data/tilesets/hns/{graphics,metatiles,headers}.h and
src/data/tilesets/hns/tileset_anims.h (the Johto animations, from HnS).

Usage (repo root): python3 -I tools/sfr/hns/import_tilesets.py [--hns /path]
"""
import json, os, re, shutil, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import hns, ours, read, write, johto_maps, KANTO_HGSS_MAPS

EMPTY = [0, 0, 0, 0]
CALLBACKS = {'InitTilesetAnim_JohtoGeneral', 'InitTilesetAnim_NationalPark', 'InitTilesetAnim_EcruteakTheater',
             'InitTilesetAnim_AzaleaTownGym', 'InitTilesetAnim_BlackthornGym', 'InitTilesetAnim_MtSilverExp'}

L = {l['id']: l for l in json.load(open(hns('data/layouts/layouts.json')))['layouts'] if 'primary_tileset' in l}
needed = set()
for grp, m in johto_maps() + [(None, m) for m in KANTO_HGSS_MAPS]:
    l = L[json.load(open(hns('data/maps', m, 'map.json')))['layout']]
    needed |= {l['primary_tileset'], l['secondary_tileset']}

H_GFX = read(hns('src/data/tilesets/graphics.h'))
H_HDR = read(hns('src/data/tilesets/headers.h'))


def convert(d):
    mt = open(os.path.join(d, 'metatiles.bin'), 'rb').read()
    at = open(os.path.join(d, 'metatile_attributes.bin'), 'rb').read()
    n = len(at) // 2
    if len(mt) == n * 24:
        return  # already converted
    assert len(mt) == n * 16, d
    out_mt, out_at = bytearray(), bytearray()
    for i in range(n):
        e = list(struct.unpack('<8H', mt[i * 16:i * 16 + 16]))
        a = struct.unpack('<H', at[i * 2:i * 2 + 2])[0]
        layer = (a >> 12) & 0xF
        A, B = e[:4], e[4:]
        if layer == 1:
            t = A + B + EMPTY
        elif layer == 2:
            t = A + EMPTY + B
        else:
            t = EMPTY + A + B
        out_mt += struct.pack('<12H', *t)
        out_at += struct.pack('<I', (a & 0xFF) | ((layer & 3) << 29))
    open(os.path.join(d, 'metatiles.bin'), 'wb').write(out_mt)
    open(os.path.join(d, 'metatile_attributes.bin'), 'wb').write(out_at)


g_out, m_out, h_out = [], [], []
for t in sorted(needed):
    n = t[len('gTileset_'):]
    path = re.search(r'gTilesetTiles_%s\[\] = INCBIN_U32\("([^"]+)/tiles' % re.escape(n), H_GFX).group(1)
    shutil.rmtree(ours(path), ignore_errors=True)
    shutil.copytree(hns(path), ours(path))
    convert(ours(path))
    pals = sorted(f for f in os.listdir(ours(path, 'palettes')) if re.fullmatch(r'\d\d\.pal', f))
    g_out.append('const u32 gTilesetTiles_%s[] = INCGFX_U32("%s/tiles.png", ".4bpp.fastSmol");\n\n'
                 'const u16 gTilesetPalettes_%s[][16] =\n{\n%s};\n'
                 % (n, path, n, ''.join('    INCGFX_U16("%s/palettes/%s", ".gbapal"),\n' % (path, p) for p in pals)))
    m_out.append('const u16 gMetatiles_%s[] = INCBIN_U16("%s/metatiles.bin");\n'
                 'const u16 gMetatileAttributes_%s[] = INCBIN_U16("%s/metatile_attributes.bin");\n' % (n, path, n, path))
    hb = re.search(r'const struct Tileset %s =\s*\{(.*?)\};' % t, H_HDR, re.S).group(1)
    sec = re.search(r'\.isSecondary = (\w+)', hb).group(1)
    cb = re.search(r'\.callback = (\w+)', hb)
    cb = cb.group(1) if cb and cb.group(1) in CALLBACKS else 'NULL'
    h_out.append('const struct Tileset %s =\n{\n    .isCompressed = TRUE,\n    .isSecondary = %s,\n'
                 '    .tiles = gTilesetTiles_%s,\n    .palettes = gTilesetPalettes_%s,\n'
                 '    .metatiles = gMetatiles_%s,\n    .metatileAttributes = gMetatileAttributes_%s,\n'
                 '    .callback = %s,\n};\n' % (t, sec, n, n, n, n, cb))

hdr = '// Super Emerald: generated by tools/sfr/hns/import_tilesets.py from Pokemon Heart & Soul.\n\n'

def write_between_markers(kind, text):
    """The tilesets go into the main src/data/tilesets/*.h files (Porymap only reads those)."""
    p = ours('src/data/tilesets/%s.h' % kind); s = read(p)
    b = '// Super Emerald: Johto (HnS) tilesets (begin, generated by tools/sfr/hns/import_tilesets.py)\n'
    e = '// Super Emerald: Johto (HnS) tilesets (end)\n'
    if b in s:
        s = s[:s.index(b)] + s[s.index(e) + len(e):]
    text = '\n'.join(l for l in text.split('\n') if not l.startswith('#include'))
    write(p, s.rstrip('\n') + '\n\n' + b + text.strip('\n') + '\n' + e)

write_between_markers('graphics', hdr + '\n'.join(g_out))
write_between_markers('metatiles', hdr + '\n'.join(m_out))
write_between_markers('headers', hdr + '\n'.join(h_out))

# ---- Johto tileset animations (HnS src/tileset_anims.c, IS_HNS block, Johto parts only)
src = read(hns('src/tileset_anims.c'))
a = src.index('// HnS Johto tileset animations')
b = src.index('// Alola Islands primary tileset anims')
blk = src[a:b]
blk = blk[:blk.rindex('#endif')] if blk.rstrip().endswith('#endif') else blk
# drop the Kanto (HnS) parts: Celadon / Cerulean / Silph Co
for name in ('CeladonCity_Hns', 'CeruleanCity_Hns', 'SilphCo_Hns', 'CeladonCityHns', 'CeruleanCityHns', 'SilphCoHns'):
    blk = re.sub(r'static void \w*%s\w*\(u16\);\n' % name, '', blk)
    blk = re.sub(r'(?:static )?const u16 (?:\*const )?s%s\w*\[\][^;]*;\n' % name.replace('_Hns', 'Hns'), '', blk)
    blk = re.sub(r'(?:void|static void) \w*%s\w*\([^)]*\)\n\{.*?\n\}\n' % name, '', blk, flags=re.S)
blk = re.sub(r'(?:static )?const u16 (?:\*const )?s(?:CeladonCity|CeruleanCity|SilphCo)Hns\w*\[\] = \{.*?\};\n', '', blk, flags=re.S)
blk = blk.replace('sSecondaryTilesetBaseTile', 'NUM_TILES_IN_PRIMARY_FRLG')
blk = re.sub(r'\bNUM_TILES_IN_PRIMARY\b', 'NUM_TILES_IN_PRIMARY_FRLG', blk)
if blk.rstrip().endswith('#endif'):
    blk = blk.rstrip()[:-len('#endif')]
write(ours('src/data/tilesets/hns/tileset_anims.h'), hdr + blk)
print('tilesets', len(needed))
