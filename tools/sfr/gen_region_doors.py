#!/usr/bin/env python3
"""Super Emerald: door animations for the Johto (HnS) and Sinnoh tilesets.

Reads the door tables of the source repos and writes src/data/field_door_regions.h:
the door graphics (copied to graphics/door_anims/hns and graphics/door_anims/sinnoh)
and table entries for our renamed tilesets.  Run from the repo root."""
import os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HNS = '/home/claude/hns/pokehns-expansion'
SIN = '/home/claude/lidermorti00/sinnoh-pokeemerald-expansion'

def read(p):
    return open(p, encoding='utf-8').read()

ours_headers = read(os.path.join(ROOT, 'src/data/tilesets/headers.h'))
OUR_TILESETS = set(re.findall(r'const struct Tileset (gTileset_\w+)', ours_headers))

def labels(repo):
    d = {}
    for m in re.finditer(r'#define (METATILE_\w+)\s+(0x[0-9A-Fa-f]+|\d+)', read(os.path.join(repo, 'include/constants/metatile_labels.h'))):
        d[m.group(1)] = int(m.group(2), 0)
    return d

def arrays(src):
    tiles = dict(re.findall(r'static const u8 (sDoorAnimTiles_\w+)\[\] = INC\w+\("graphics/door_anims/([\w/]+?)(?:\.png|\.4bpp)"', src))
    pals = {m.group(1): [int(x) for x in m.group(2).split(',')]
            for m in re.finditer(r'static const u8 (sDoorAnimPalettes_\w+)\[\] = \{([^}]*)\}', src)}
    return tiles, pals

out_gfx, out_tbl = [], []
used_tiles, used_pals = {}, {}

def add(repo, suffix, sound, size, metatile, tileset, tiles_sym, pal, tiles_path, alt_start):
    key = tiles_sym + suffix
    if key not in used_tiles:
        dst = 'graphics/door_anims/%s/%s.png' % (suffix.lower(), os.path.basename(tiles_path))
        os.makedirs(os.path.dirname(os.path.join(ROOT, dst)), exist_ok=True)
        shutil.copy(os.path.join(repo, 'graphics/door_anims', tiles_path + '.png'), os.path.join(ROOT, dst))
        used_tiles[key] = dst
        out_gfx.append('static const u8 %s[] = INCGFX_U8("%s", ".4bpp");' % (key, dst))
    pkey = 'sDoorAnimPalettes_%s_%s' % (suffix, '_'.join(map(str, pal)))
    if pkey not in used_pals:
        used_pals[pkey] = 1
        out_gfx.append('static const u8 %s[] = {%s};' % (pkey, ', '.join(map(str, pal))))
    out_tbl.append('    {.metatileNum = 0x%03X, .tileset = &%s, .sound = %s, .size = %s, .tiles = %s, .palettes = %s%s},'
                   % (metatile, tileset, sound, size, key, pkey, ', .altTileStart = TRUE' if alt_start else ''))

# --- Johto (HnS): FRLG-style doors, size 1 = one metatile, 2 = two metatiles; tiles go to tile 434
src = read(os.path.join(HNS, 'src/field_door.c'))
tiles, pals = arrays(src)
lab = labels(HNS)
blk = src[src.index('#elif IS_HNS', src.index('sDoorAnimGraphicsTable[] =')):]
blk = blk[:blk.index('#endif')]
n = 0
for m in re.finditer(r'\{(METATILE_\w+|0x[0-9A-Fa-f]+),\s*&(gTileset_\w+),\s*(DOOR_SOUND_\w+),\s*(\d),\s*(sDoorAnimTiles_\w+),\s*(sDoorAnimPalettes_\w+)\}', blk):
    mt, ts, snd, size, t, p = m.groups()
    if not ts.endswith('_Hns') or ts not in OUR_TILESETS or t not in tiles or p not in pals:
        continue
    num = lab[mt] if mt in lab else int(mt, 0)
    pal = (pals[p] + pals[p])[:8]
    add(HNS, 'Hns', snd, 'DOOR_SIZE_1x1' if size == '1' else 'DOOR_SIZE_1x2', num, ts, t, pal, tiles[t], True)
    n += 1
print('hns doors', n)

# --- Sinnoh
src = read(os.path.join(SIN, 'src/field_door.c'))
tiles, pals = arrays(src)
lab = labels(SIN)
tbl = src[src.index('sDoorAnimGraphicsTable[] ='):]
tbl = tbl[:tbl.index('\n};')]
n = 0
for m in re.finditer(r'\{\s*\.metatileNum = (\w+),\s*\.tileset = &(gTileset_\w+),\s*\.sound = (DOOR_SOUND_\w+),\s*\.size = (DOOR_SIZE_\w+),\s*\.tiles = (sDoorAnimTiles_\w+),\s*\.palettes = (sDoorAnimPalettes_\w+)\s*\}', tbl):
    mt, ts, snd, size, t, p = m.groups()
    ts2 = ts + '_Sinnoh'
    if ts2 not in OUR_TILESETS or t not in tiles or p not in pals:
        continue
    num = lab[mt] if mt in lab else int(mt, 0)
    pal = (pals[p] + pals[p])[:8]
    if size == 'DOOR_SIZE_1x2':
        pal = pal[:4] + pal[:4]       # the Sinnoh repo draws both halves with the first four palettes
        size = 'DOOR_SIZE_1x2'
    elif size == 'DOOR_SIZE_1x2_SN':
        size = 'DOOR_SIZE_1x2'        # same as our 1x2 (bottom half uses palettes 4-7)
    elif size not in ('DOOR_SIZE_1x1', 'DOOR_SIZE_2x2_LEFT', 'DOOR_SIZE_2x2_RIGHT'):
        continue
    add(SIN, 'Sinnoh', snd, size, num, ts2, t, pal, tiles[t], False)
    n += 1
print('sinnoh doors', n)

hdr = '// Super Emerald: generated by tools/sfr/gen_region_doors.py - do not edit by hand.\n'
with open(os.path.join(ROOT, 'src/data/field_door_regions_gfx.h'), 'w') as f:
    ts = sorted(set(re.findall(r'&(gTileset_\w+)', '\n'.join(out_tbl))))
    f.write(hdr + ''.join('extern const struct Tileset %s;\n' % t for t in ts) + '\n'.join(out_gfx) + '\n')
with open(os.path.join(ROOT, 'src/data/field_door_regions_table.h'), 'w') as f:
    f.write(hdr + '\n'.join(out_tbl) + '\n')
